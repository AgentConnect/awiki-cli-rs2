#!/usr/bin/env node
'use strict';

const { readServerConfig } = require('./config.js');

const config = readServerConfig(process.argv[2]);
const publicPath = `${config.public_base_path}/`;
const webRoot = `${config.web_root.replace(/\/+$/, '')}/`;
process.stdout.write('# Generated by scripts/release/cli/render-nginx-snippet.js.\n');
const tenants = require('./documents.js').tenants(JSON.parse(require('fs').readFileSync(config.document_tenants, 'utf8')));
const tenant = tenants.find(t => t.origin === config.public_origin);
if (!tenant) throw new Error('public origin missing from explicit document tenants');
for (const document of ['onboarding.md', 'skill.md']) {
  process.stdout.write(`location = ${publicPath}${document} {\n`);
  process.stdout.write(`    alias ${webRoot}docs/${new URL(tenant.origin).hostname}/${document};\n`);
  process.stdout.write('    types {}\n    default_type text/markdown;\n    charset utf-8;\n');
  process.stdout.write('    add_header Cache-Control "no-store" always;\n');
  process.stdout.write('    add_header X-Content-Type-Options "nosniff" always;\n}\n');
}
process.stdout.write('# Channel metadata remains mutable; only versioned platform packages use download limits and immutable caching.\n');
for (const channel of ['stable', 'beta']) {
  process.stdout.write(`location = ${publicPath}${channel}/ {\n`);
  process.stdout.write(`    rewrite ^ ${publicPath}${channel}/manifest.json last;\n`);
  process.stdout.write('}\n');
  process.stdout.write(`location ^~ ${publicPath}${channel}/artifacts/ {\n`);
  process.stdout.write(`    alias ${webRoot}${channel}/artifacts/;\n`);
  process.stdout.write('    autoindex off;\n');
  process.stdout.write(`    limit_conn cli_download_per_ip ${config.cli_download_max_per_ip};\n`);
  process.stdout.write(`    limit_conn cli_download_total ${config.cli_download_max_total};\n`);
  process.stdout.write('    limit_conn_status 429;\n');
  process.stdout.write(`    limit_rate_after ${config.cli_download_rate_after};\n`);
  process.stdout.write(`    limit_rate ${config.cli_download_rate};\n`);
  process.stdout.write('    add_header X-Content-Type-Options "nosniff" always;\n');
  process.stdout.write('    add_header Cache-Control "public, max-age=31536000, immutable" always;\n');
  process.stdout.write('}\n');
}
process.stdout.write(`location ^~ ${publicPath} {\n`);
process.stdout.write(`    alias ${webRoot};\n`);
process.stdout.write('    autoindex off;\n');
process.stdout.write('    add_header X-Content-Type-Options "nosniff" always;\n');
process.stdout.write('    add_header Cache-Control "no-cache, no-store, must-revalidate" always;\n');
process.stdout.write('}\n');
